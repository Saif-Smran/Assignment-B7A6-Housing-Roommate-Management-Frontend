import { spawn } from "node:child_process";
import { access, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const graphifySource = "git+https://github.com/Graphify-Labs/graphify";
const graphifyOutput = path.join(projectRoot, "graphify-out");
const projectCodebasePath = path.join(projectRoot, "projectCodeBase.md");

function commandResult(command, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      cwd: projectRoot,
      env: { ...process.env, GRAPHIFY_OUT: graphifyOutput },
      stdio: "inherit",
      windowsHide: true,
    });

    child.on("error", reject);
    child.on("close", (code) => resolve(code ?? 1));
  });
}

async function runGraphifyCommand(args) {
  const pathVariable = process.env.Path ?? process.env.PATH ?? "";
  const pathEntries = pathVariable.split(path.delimiter).filter(Boolean);
  const executableSuffix = process.platform === "win32" ? ".exe" : "";

  for (const command of ["uvx", "graphify"]) {
    for (const directory of pathEntries) {
      try {
        await access(path.join(directory, `${command}${executableSuffix}`));
        if (command === "uvx") {
          return commandResult("uvx", [
            "--from",
            graphifySource,
            "graphify",
            ...args,
          ]);
        }
        return commandResult("graphify", args);
      } catch {}
    }
  }

  throw new Error("Graphify requires `uvx` or `graphify` on PATH.");
}

async function runGraphify() {
  const extractCode = await runGraphifyCommand([
    ".",
    "--code-only",
    "--directed",
  ]);
  if (extractCode !== 0) {
    return extractCode;
  }

  return runGraphifyCommand(["cluster-only", "."]);
}

async function writeProjectCodebaseIndex() {
  const outputFiles = [
    ["GRAPH_REPORT.md", "Plain-language architecture report"],
    ["graph.html", "Interactive code graph"],
    ["graph.json", "GraphRAG-ready graph data"],
  ];
  const reportPath = path.join(graphifyOutput, "GRAPH_REPORT.md");
  let reportSummary =
    "Graphify generated the report and graph artifacts listed below.";

  try {
    const report = await readFile(reportPath, "utf8");
    const summary = report
      .split("\n")
      .filter((line) => line.trim())
      .slice(0, 8)
      .join("\n");
    if (summary) {
      reportSummary = summary;
    }
  } catch {
    reportSummary =
      "The Graphify report was not available after the graph command finished.";
  }

  const sections = [
    "# Project Codebase",
    "",
    "> This file is a lightweight entry point generated by `bun run code`. Read the Graphify report before opening individual source files.",
    "",
    "## Graphify Outputs",
    "",
    ...outputFiles.map(
      ([file, description]) =>
        `- [graphify-out/${file}](graphify-out/${file}) - ${description}`,
    ),
    "",
    "## Report Preview",
    "",
    reportSummary,
    "",
    "## Refresh",
    "",
    "Run `bun run code` after code changes. The command reruns Graphify from `https://github.com/Graphify-Labs/graphify` and refreshes this index.",
    "",
  ];

  await writeFile(projectCodebasePath, sections.join("\n"), "utf8");
}

const exitCode = await runGraphify();
if (exitCode !== 0) {
  process.exitCode = exitCode;
  process.exit();
}

await writeProjectCodebaseIndex();
console.log("Updated projectCodeBase.md and graphify-out/.");
